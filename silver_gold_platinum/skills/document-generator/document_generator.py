def generate_custom_document(
    title: str,
    template: str,
    content_data: dict,
    output_format: str = 'md',
    require_approval: bool = True
) -> dict:
    """
    Generate a custom document from a template string.
    
    Args:
        title: Document title
        template: Template string with {placeholders}
        content_data: Dict of placeholder -> value
        output_format: 'md', 'pdf', or 'txt' (default: 'md')
        require_approval: If True, requires human approval (default: True)
    
    Returns:
        dict: {'success': bool, 'file_path': str, 'error': str}
    """
    
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    filename = f"{title.replace(' ', '_')}_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    
    # Add title and timestamp to content
    full_content = f"# {title}\n\n**Generated:** {timestamp}\n\n{template}"
    
    # Substitute placeholders
    try:
        content = full_content.format(**content_data)
    except KeyError as e:
        return {'success': False, 'error': f'Missing placeholder: {e}'}
    
    # Prepare preview
    preview_data = {
        'title': title,
        'type': 'Custom Document',
        'placeholders_filled': len(content_data),
        'content_preview': content[:300] + ('...\n[Truncated]' if len(content) > 300 else '')
    }
    
    # HUMAN-IN-THE-LOOP APPROVAL
    if require_approval:
        print("\n" + "=" * 70)
        print("DOCUMENT GENERATION - HUMAN APPROVAL REQUIRED")
        print("=" * 70)
        print(f"\n📄 DOCUMENT: {title}")
        print(f"📋 TYPE: Custom Document")
        print(f"⏰ GENERATED: {timestamp}")
        print(f"\n📊 PLACEHOLDERS FILLED: {len(content_data)}")
        print(f"\n📝 CONTENT PREVIEW:")
        print("-" * 70)
        print(preview_data['content_preview'])
