def generate_ceo_briefing(
    title: str,
    executive_summary: str,
    key_metrics: dict,
    highlights: list,
    challenges: list,
    action_items: list,
    output_format: str = 'md',
    require_approval: bool = True
) -> dict:
    """
    Generate a CEO Briefing document.
    
    Args:
        title: Briefing title
        executive_summary: High-level summary
        key_metrics: Dict of metric name -> value
        highlights: List of key highlights/wins
        challenges: List of challenges/blockers
        action_items: List of action items
        output_format: 'md', 'pdf', or 'txt' (default: 'md')
        require_approval: If True, requires human approval (default: True)
    
    Returns:
        dict: {'success': bool, 'file_path': str, 'error': str}
    """
    
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    filename = f"CEO_Briefing_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    
    # Generate Markdown content
    content = f"""# {title}

**Generated:** {timestamp}  
**Document Type:** CEO Briefing

---

## Executive Summary

{executive_summary}

---

## Key Metrics

"""
    
    for metric, value in key_metrics.items():
        content += f"- **{metric}:** {value}\n"
    
    content += "\n---\n\n## Highlights\n\n"
    for highlight in highlights:
        content += f"✅ {highlight}\n"
    
    content += "\n---\n\n## Challenges\n\n"
    for challenge in challenges:
        content += f"⚠️ {challenge}\n"
    
    content += "\n---\n\n## Action Items\n\n"
    for i, item in enumerate(action_items, 1):
        content += f"{i}. {item}\n"
    
    content += f"\n---\n\n*This briefing was auto-generated by the Personal AI Employee system.*\n"
    
    # Prepare preview for approval
    preview_data = {
        'title': title,
        'type': 'CEO Briefing',
        'executive_summary_preview': executive_summary[:200] + ('...' if len(executive_summary) > 200 else ''),
        'metrics_count': len(key_metrics),
        'highlights_count': len(highlights),
        'challenges_count': len(challenges),
        'action_items_count': len(action_items)
    }
    
    # HUMAN-IN-THE-LOOP APPROVAL
    if require_approval:
        print("\n" + "=" * 70)
        print("DOCUMENT GENERATION - HUMAN APPROVAL REQUIRED")
        print("=" * 70)
        print(f"\n📄 DOCUMENT: {title}")
        print(f"📋 TYPE: CEO Briefing")
        print(f"⏰ GENERATED: {timestamp}")
        print(f"\n📊 CONTENT SUMMARY:")
        print(f"   - Metrics: {preview_data['metrics_count']}")
        print(f"   - Highlights: {preview_data['highlights_count']}")
        print(f"   - Challenges: {preview_data['challenges_count']}")
        print(f"   - Action Items: {preview_data['action_items_count']}")
        print(f"\n📝 EXECUTIVE SUMMARY PREVIEW:")
        print("-" * 70)
        print(preview_data['executive_summary_preview'])
        print("-" * 70)
        print(f"\nOutput format: {output_format.upper()}")
        print(f"Output directory: {OUTPUT_DIR}")
        print("\nApprove generating this document?")
        
        while True:
            response = input("Type 'yes' to approve, 'no' to cancel: ").strip().lower()
            if response in ['yes', 'y']:
                print("Document generation APPROVED\n")
                break
            elif response in ['no', 'n']:
                print("Document generation CANCELLED by user\n")
                return {
                    'success': False,
                    'error': 'User cancelled document generation',
                    'details': preview_data
                }
            else:
                print("Invalid response. Please type 'yes' or 'no'.")
    
    # Save the document
    try:
        if output_format == 'md':
            file_path = OUTPUT_DIR / f"{filename}.md"
            file_path.write_text(content, encoding='utf-8')
        elif output_format == 'txt':
            file_path = OUTPUT_DIR / f"{filename}.txt"
            # Convert markdown to plain text
            plain_text = content.replace('#', '').replace('*', '').replace('---', '')
            file_path.write_text(plain_text, encoding='utf-8')
        elif output_format == 'pdf':
            # For PDF, save as markdown and note conversion needed
            file_path = OUTPUT_DIR / f"{filename}.md"
            file_path.write_text(content, encoding='utf-8')
            print("[Note] PDF conversion requires additional dependencies (e.g., pandoc, wkhtmltopdf)")
            print("[Note] Document saved as Markdown. Convert manually if PDF needed.")
        else:
            return {'success': False, 'error': f'Unsupported format: {output_format}'}
        
        print(f"✅ Document generated successfully!")
        print(f"📁 Saved to: {file_path}")
        
        return {
            'success': True,
            'file_path': str(file_path),
            'filename': file_path.name,
            'format': output_format,
            'details': preview_data
        }
        
    except Exception as e:
        error_msg = f"Failed to generate document: {type(e).__name__}: {str(e)}"
        print(f"❌ {error_msg}")
        return {
            'success': False,
            'error': error_msg,
            'details': preview_data
        }


